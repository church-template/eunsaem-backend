-- (CHURCH_NAME / CHURCH_SLUG / CORS_ALLOWED_ORIGIN). JPA 엔티티로 매핑하지 않는다 — JdbcClient 전용.
CREATE TABLE churches (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    slug            VARCHAR(40)  NOT NULL,
    frontend_origin VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uq_churches_slug UNIQUE (slug),
    CONSTRAINT ck_churches_slug CHECK (slug ~ '^[a-z0-9-]{1,40}$')
);
